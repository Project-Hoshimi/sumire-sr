#!/usr/bin/env node
// Generate docs/ENDPOINTS.md from the protocol endpoint list, the server's
// literal `register('Service:Method', ...)` calls, and the recorded endpoint
// levels.
//
// Usage: node scripts/gen-endpoints.mjs [--endpoints <json|ts>] [--services <dir>] [--levels <file>] [--out <file>]
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, relative, resolve } from 'node:path';

const ROOT = process.cwd();

function arg(name, fallback) {
  const i = process.argv.indexOf(`--${name}`);
  return i !== -1 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
}

function firstExisting(candidates) {
  for (const candidate of candidates) {
    const full = resolve(ROOT, candidate);
    if (existsSync(full)) return full;
  }
  return null;
}

const endpointsPath = arg(
  'endpoints',
  firstExisting([
    'packages/protocol/schemas/endpoints.json',
    'phaseA1/out/schemas/endpoints.json',
  ]),
);
if (!endpointsPath) {
  console.error('gen-endpoints: no endpoints.json found (tried packages/protocol/schemas, phaseA1/out/schemas)');
  process.exit(1);
}

const servicesDir = resolve(
  ROOT,
  arg(
    'services',
    firstExisting(['packages/server/src/services', 'fastify-api/src/services']) ??
      'packages/server/src/services',
  ),
);
if (!existsSync(servicesDir)) {
  console.error(`gen-endpoints: services directory not found: ${servicesDir}`);
  process.exit(1);
}

const levelsArg = arg(
  'levels',
  firstExisting([
    'packages/server/src/services/endpointLevels.ts',
    'fastify-api/src/services/endpointLevels.ts',
  ]),
);
const levelsPath = levelsArg ? resolve(ROOT, levelsArg) : null;

const outPath = resolve(ROOT, arg('out', 'docs/ENDPOINTS.md'));

function parseEndpoints(file) {
  const text = readFileSync(file, 'utf8');
  if (file.endsWith('.json')) {
    const parsed = JSON.parse(text);
    return parsed.map((service) => ({
      service: service.service,
      methods: service.methods.map((method) => method.name),
    }));
  }
  // Fallback: parse the generated endpoints.ts object literal.
  const services = [];
  let current = null;
  for (const line of text.split('\n')) {
    const serviceMatch = line.match(/^  '([^']+)': \{$/);
    if (serviceMatch) {
      current = { service: serviceMatch[1], methods: [] };
      services.push(current);
      continue;
    }
    if (!current) continue;
    const methodMatch = line.match(/^    '([^']+)': \{ request:/);
    if (methodMatch) current.methods.push(methodMatch[1]);
  }
  return services;
}

const VALID_LEVELS = new Set(['stub', 'sandbox-ok', 'parity']);
const LEVEL_LINE_RE = /^  '([^']+)': '([^']+)',?[ \t]*$/gm;
const levels = new Map();
if (levelsPath) {
  const text = readFileSync(levelsPath, 'utf8');
  for (const match of text.matchAll(LEVEL_LINE_RE)) {
    const name = match[1];
    const level = match[2];
    if (!VALID_LEVELS.has(level)) {
      console.error(`gen-endpoints: invalid level for ${name}: ${level}`);
      process.exit(1);
    }
    if (levels.has(name)) {
      console.error(`gen-endpoints: duplicate endpoint in levels file: ${name}`);
      process.exit(1);
    }
    levels.set(name, level);
  }
}

function walk(dir) {
  const files = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...walk(full));
    else if (entry.name.endsWith('.ts')) files.push(full);
  }
  return files;
}

const REGISTER_RE = /\bregister\(\s*(['"])([^'"]+)\1/g;
const registered = new Set();
for (const file of walk(servicesDir)) {
  if (basename(file) === 'endpointLevels.ts') continue;
  const text = readFileSync(file, 'utf8');
  for (const match of text.matchAll(REGISTER_RE)) registered.add(match[2]);
}

const rows = [];
const seen = new Set();
for (const { service, methods } of parseEndpoints(endpointsPath)) {
  for (const method of methods) {
    const key = `${service}:${method}`;
    if (seen.has(key)) continue;
    seen.add(key);
    const status = levels.get(key) ?? (registered.has(key) ? 'unrated' : 'missing');
    rows.push({ service, method, status });
  }
}

for (const name of levels.keys()) {
  if (!seen.has(name)) {
    console.error(`gen-endpoints: unknown endpoint in levels file: ${name}`);
    process.exit(1);
  }
}

rows.sort((a, b) => a.service.localeCompare(b.service) || a.method.localeCompare(b.method));
const count = (status) => rows.filter((row) => row.status === status).length;
const parity = count('parity');
const sandboxOk = count('sandbox-ok');
const stub = count('stub');
const unrated = count('unrated');
const missing = count('missing');

const relEndpoint = relative(ROOT, endpointsPath);
const relServices = relative(ROOT, servicesDir);
const lines = [
  '# Endpoint implementation status',
  '',
  'Generated by `npm run docs:endpoints` from the protocol endpoint list, the',
  'literal `register(\'Service:Method\', ...)` calls in the server services, and the',
  'recorded levels in the levels file.',
  'Do not edit by hand.',
  'Levels are defined in [ROADMAP.md](../ROADMAP.md). `unrated` means a handler exists but no level has been recorded yet.',
  '',
  `- Endpoint list: \`${relEndpoint}\``,
  `- Handler scan: \`${relServices}\``,
  ...(levelsPath ? [`- Levels: \`${relative(ROOT, levelsPath)}\``] : []),
  '',
  '| Service | Endpoint | Status |',
  '| --- | --- | --- |',
  ...rows.map((row) => `| ${row.service.replace(/\|/g, '\\|')} | ${row.method.replace(/\|/g, '\\|')} | ${row.status} |`),
  '',
  `**Totals:** ${rows.length} endpoints — ${parity} parity, ${sandboxOk} sandbox-ok, ${stub} stub, ${unrated} unrated, ${missing} missing.`,
  '',
];

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, lines.join('\n'));
console.log(
  `gen-endpoints: ${rows.length} endpoints (${parity} parity, ${sandboxOk} sandbox-ok, ${stub} stub, ${unrated} unrated, ${missing} missing) -> ${relative(ROOT, outPath)}`,
);
