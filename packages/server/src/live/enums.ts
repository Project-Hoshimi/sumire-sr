/** Reverse lookup (wire value -> member name), mirroring penum.*_name in Go. */
export function enumName(table: Record<string, number>, value: number): string | undefined {
  for (const [name, v] of Object.entries(table)) {
    if (v === value) return name;
  }
  return undefined;
}
