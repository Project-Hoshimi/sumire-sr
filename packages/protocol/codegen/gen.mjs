#!/usr/bin/env node
// Codegen — schemas/*.json → src/gen/*.ts (per-message codec modules)
// Deterministic: same catalog in → same tree out. Side-effect-free upstream.
// Each generated module registers its MessageShape into the runtime registry on
// import; registry.ts imports all of them so a single import wires everything.
//
// Also emits:
//   src/gen/registry.ts    — imports + registers all messages (single import point)
//   src/gen/endpoints.ts   — service:method → {request, response} qualified keys
//   src/gen/enums.ts       — enum name → {value: originalName?} map (metadata)
//
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SCHEMAS = path.join(ROOT, 'schemas');
const GEN = path.join(ROOT, 'src', 'gen');

const messages = JSON.parse(fs.readFileSync(path.join(SCHEMAS, 'messages.json'), 'utf8'));
const endpoints = JSON.parse(fs.readFileSync(path.join(SCHEMAS, 'endpoints.json'), 'utf8'));
const enums = JSON.parse(fs.readFileSync(path.join(SCHEMAS, 'enums.json'), 'utf8'));
fs.mkdirSync(GEN, { recursive: true });

const PAD = '  ';
const nl = '\n';

// Escape a JS single-quoted string literal (fields are identifiers, but be safe)
function q(s) {
  return `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;
}

// Object-literal enum key. Numeric literals cannot carry a sign (`-1:` is a
// syntax error), so negative values are emitted as quoted numeric strings.
// The sign is preserved: `'-1': 'All'`.
function emitEnumKey(value) {
  return Number(value) < 0 ? q(String(value)) : String(value);
}

// emit a FieldShape literal (compact)
function emitShape(f, indent) {
  const pad = PAD.repeat(indent);
  const parts = [];
  if (f.number !== undefined) parts.push(`number:${f.number}`);
  if (f.name !== undefined) parts.push(`name:${q(f.name)}`);
  if (f.wire !== undefined) parts.push(`wire:${q(f.wire)}`);
  if (f.label !== undefined) parts.push(`label:${q(f.label)}`);
  if (f.zigzag !== undefined) parts.push(`zigzag:${f.zigzag === null ? 'null' : (f.zigzag ? 'true' : 'false')}`);
  if (f.message !== undefined) parts.push(`message:${q(f.message)}`);
  if (f.enum !== undefined) parts.push(`enum:${q(f.enum)}`);
  if (f.repeated !== undefined) parts.push(`repeated:true`);
  if (f.map !== undefined) parts.push(`map:true`);
  if (f.key) parts.push(`key:${emitShape(f.key, 0)}`);
  if (f.value) parts.push(`value:${emitShape(f.value, 0)}`);
  if (f.element) parts.push(`element:${emitShape(f.element, 0)}`);
  return `{${parts.join(',')}}`;
}

function emitMessage(m) {
  const id = sanitizeId(m.qualifiedName);
  const fieldLines = m.fields.map(f => `    ${emitShape(f, 2)},`);
  return `// @ts-nocheck
// Auto-generated by codegen/gen.mjs — do not edit.
// ${m.qualifiedName} (${m.namespace}, TypeDefIndex ${m.typeDefIndex})
import { register, type MessageShape, type FieldShape } from '../runtime/proto.ts';

const shape: MessageShape = {
  name: ${q(m.qualifiedName)},
  namespace: ${q(m.namespace)},
  ${m.oneof ? 'oneof: true,' : ''}
  fields: [
${fieldLines.join(nl)}
  ],
};

register(shape);

export default shape;
export const name = ${q(m.qualifiedName)};
`;
}

function sanitizeId(s) {
  // keep [A-Za-z0-9_], collapse others to _
  return s.replace(/[^A-Za-z0-9_]/g, '_');
}

// deterministic order
messages.sort((a, b) => (a.qualifiedName < b.qualifiedName ? -1 : a.qualifiedName > b.qualifiedName ? 1 : 0));
const fileNames = [];
for (const m of messages) {
  const fn = `${sanitizeId(m.qualifiedName)}.ts`;
  fileNames.push(fn);
  fs.writeFileSync(path.join(GEN, fn), emitMessage(m));
}

// registry.ts
const importLines = fileNames.map(f => `import './${f}';`);
fs.writeFileSync(path.join(GEN, 'registry.ts'), `// @ts-nocheck
// Auto-generated by codegen/gen.mjs — imports + registers every message codec.
${importLines.join(nl)}
`);

// endpoints.ts
const epLines = [];
for (const svc of endpoints) {
  const methods = svc.methods.map(me => `    ${q(me.name)}: { request: ${q(me.request)}, response: ${q(me.response)} },`).join(nl);
  epLines.push(`  ${q(svc.service)}: {`);
  epLines.push(methods);
  epLines.push(`  },`);
}
fs.writeFileSync(path.join(GEN, 'endpoints.ts'), `// @ts-nocheck
// Auto-generated by codegen/gen.mjs — service:method → request/response qualified keys.
export type EndpointMap = Record<string, Record<string, { request: string; response: string }>>;
export const endpoints: EndpointMap = {
${epLines.join(nl)}
};
`);

// enums.ts
const enumLines = [];
for (const e of enums) {
  const values = e.values.map(v => `    ${emitEnumKey(v.value)}: ${q(v.originalName || v.name)},`).join(nl);
  enumLines.push(`  ${q(e.namespace ? `${e.namespace}.${e.name}` : e.name)}: {`);
  enumLines.push(values);
  enumLines.push(`  },`);
}
fs.writeFileSync(path.join(GEN, 'enums.ts'), `// @ts-nocheck
// Auto-generated by codegen/gen.mjs — enum numeric value → canonical name.
export const enumValues: Record<string, Record<number, string>> = {
${enumLines.join(nl)}
};
`);

console.log(`[A1.1] generated ${messages.length} message modules in ${GEN}`);
console.log(`[A1.1] registry.ts / endpoints.ts / enums.ts written`);
